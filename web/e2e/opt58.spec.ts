import { expect, test } from '@playwright/test'
import { api, registerAccount } from './support'

test('OPT58 页签和五类素材筛选刷新保留，复制给成员条件一致且不增加历史', async ({ page, browser }) => {
  const account = await registerAccount(page)
  await api(page, 'POST', '/inbox', { account_id: account.id, content: '成员也能看到的灵感' })
  await page.goto(`/a/${account.id}/topics`)
  const historyLength = await page.evaluate(() => history.length)
  await page.getByRole('button', { name: /^收件箱/ }).click()
  await expect.poll(() => new URL(page.url()).searchParams.get('tab')).toBe('inbox')
  expect(await page.evaluate(() => history.length)).toBe(historyLength)
  await page.reload()
  await expect(page.getByText('成员也能看到的灵感', { exact: true })).toBeVisible()
  const inboxURL = page.url()
  await api(page, 'POST', '/materials', { account_id: account.id, kind: 'case', content: '匹配关键词和标签的案例', tags: ['目标标签'] })
  await api(page, 'POST', '/materials', { account_id: account.id, kind: 'opinion', content: '匹配关键词但类型不同', tags: ['目标标签'] })
  await api(page, 'POST', '/materials', { account_id: account.id, kind: 'case', content: '匹配关键词但标签不同', tags: ['其他标签'] })
  await page.goto(`/a/${account.id}/materials`)
  const materialHistory = await page.evaluate(() => history.length)
  await page.getByRole('button', { name: '本账号', exact: true }).click()
  await page.getByRole('combobox').nth(0).selectOption('case')
  await page.getByRole('combobox').nth(1).selectOption('unused')
  await page.getByPlaceholder('搜索内容、来源、标签').fill('匹配关键词')
  await page.getByRole('button', { name: '目标标签', exact: true }).click()
  const url = page.url()
  expect(Object.fromEntries(new URL(url).searchParams)).toEqual({ scope: 'account', kind: 'case', usage: 'unused', q: '匹配关键词', tag: '目标标签' })
  expect(await page.evaluate(() => history.length)).toBe(materialHistory)
  await page.reload()
  await expect(page.getByRole('combobox').nth(0)).toHaveValue('case')
  await expect(page.getByRole('combobox').nth(1)).toHaveValue('unused')
  await expect(page.getByPlaceholder('搜索内容、来源、标签')).toHaveValue('匹配关键词')
  await expect(page.getByText('匹配关键词和标签的案例', { exact: true })).toBeVisible()
  await expect(page.getByText('匹配关键词但标签不同', { exact: true })).toHaveCount(0)
  const invite = await api(page, 'POST', '/workspaces/current/invites', { role: 'viewer', max_uses: 1 })
  const member = await browser.newContext()
  try {
    const joined = await member.request.post(new URL('/api/v1/auth/register', url).toString(), { data: { username: `opt58-member-${Date.now()}`, password: 'local-e2e-password-123', invite_code: invite.code } })
    expect(joined.ok()).toBeTruthy()
    const shared = await member.newPage()
    await shared.goto(url)
    await expect(shared.getByRole('combobox').nth(0)).toHaveValue('case')
    await expect(shared.getByRole('combobox').nth(1)).toHaveValue('unused')
    await expect(shared.getByPlaceholder('搜索内容、来源、标签')).toHaveValue('匹配关键词')
    await expect(shared.getByText('匹配关键词和标签的案例', { exact: true })).toBeVisible()
    await expect(shared.getByText('匹配关键词但标签不同', { exact: true })).toHaveCount(0)
    await shared.goto(inboxURL)
    await expect(shared.getByText('成员也能看到的灵感', { exact: true })).toBeVisible()
  } finally { await member.close() }
  await page.goto(`/a/${account.id}/materials?scope=account&tag=`)
  await expect.poll(() => new URL(page.url()).searchParams.get('tag')).toBe('')
  await expect(page.getByRole('button', { name: '全部标签', exact: true })).not.toHaveClass(/bg-ink-600/)
})

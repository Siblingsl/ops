import { expect, test, type Page } from '@playwright/test'
import { api, registerAccount } from './support'

const fields = (name: string) => ({
  name, summary: '完整性回归', triggers: '测试场景时使用', instructions: '保留原始完整正文。',
  platforms: [], content_formats: [], task_types: [], task_enabled: true, agent_enabled: true, status: 'active',
})
const editor = (page: Page) => page.getByRole('dialog', { name: '技能编辑' })
async function openNew(page: Page) {
  await page.goto('/settings/skills')
  await page.getByRole('button', { name: '新建技能', exact: true }).click()
  return editor(page)
}
async function createPersonal(page: Page, name: string) {
  return (await api(page, 'POST', '/skills', { scope: 'personal', ...fields(name) })).skill
}

test('TestSkillPublicImportRequiresExplicitConfirmationAndResets', async ({ page }) => {
  await registerAccount(page)
  const dialog = await openNew(page)
  await dialog.getByLabel('保存范围').selectOption('workspace')
  await dialog.getByLabel('导入 Markdown 内容').fill('---\nformat_version: 1\nname: 公开导入门控\nsummary: 完整性回归\ntriggers: 测试\n---\n只有显式确认后公开。')
  await dialog.getByRole('button', { name: '解析预览' }).click()
  const save = dialog.getByRole('button', { name: '创建技能', exact: true })
  await expect(save).toBeDisabled()
  const confirmation = dialog.locator('label', { hasText: '我确认将以上技能内容公开给' }).getByRole('switch')
  await confirmation.click()
  await expect(save).toBeEnabled()
  await dialog.getByLabel(/^完整指令正文/).fill('最终确认的公开正文。')
  await expect(confirmation).toHaveAttribute('aria-checked', 'false')
  await expect(save).toBeDisabled()
  expect((await api(page, 'GET', '/skills?view=library&scope=workspace')).total).toBe(0)
  await confirmation.click()
  const posted = page.waitForResponse(r => r.url().endsWith('/api/v1/skills') && r.request().method() === 'POST')
  await save.click()
  expect((await posted).status()).toBe(200)
  const list = await api(page, 'GET', '/skills?view=library&scope=workspace')
  expect(list.total).toBe(1)
  const full = await api(page, 'GET', `/skills/${list.items[0].id}`)
  expect(full.instructions).toBe('最终确认的公开正文。')
  expect(full.origin).toBe('imported')
})

test('TestSkillEditLoadsFullDefinitionAndSavesAllowedFieldsOnly', async ({ page }) => {
  await registerAccount(page)
  const skill = await createPersonal(page, '可完整编辑')
  await page.goto('/settings/skills')
  await page.locator('div.flex.items-start.gap-3.px-5', { hasText: skill.name }).getByTitle('编辑', { exact: true }).click()
  const dialog = editor(page)
  await expect(dialog.getByLabel(/^完整指令正文/)).toHaveValue(fields('').instructions)
  await dialog.getByLabel(/^完整指令正文/).fill('修改后的完整正文。')
  const saved = page.waitForResponse(r => r.url().endsWith(`/api/v1/skills/${skill.id}`) && r.request().method() === 'PUT')
  await dialog.getByRole('button', { name: '保存修改', exact: true }).click()
  const response = await saved
  expect(response.status()).toBe(200)
  expect(Object.keys(response.request().postDataJSON()).sort()).toEqual([...Object.keys(fields('')), 'base_revision', 'impact_token'].sort())
  await expect(dialog).toBeHidden()
  const actual = await api(page, 'GET', `/skills/${skill.id}`)
  expect(actual.instructions).toBe('修改后的完整正文。')
  expect(actual.revision).toBe(2)
})

test('TestSkillStaleRetainsDraftAndRefreshesGuardsExplicitly', async ({ page }) => {
  await registerAccount(page)
  const skill = await createPersonal(page, '并发编辑')
  await page.goto('/settings/skills')
  await page.locator('div.flex.items-start.gap-3.px-5', { hasText: skill.name }).getByTitle('编辑', { exact: true }).click()
  const dialog = editor(page)
  await expect(dialog.getByLabel(/^完整指令正文/)).toHaveValue(fields('').instructions)
  await expect(dialog.getByText(/保存将影响/)).toBeVisible()
  await dialog.getByLabel(/^完整指令正文/).fill('当前页面保留的草稿。')
  const impact = await api(page, 'GET', `/skills/${skill.id}/impact?action=update`)
  await api(page, 'PUT', `/skills/${skill.id}`, { ...fields(skill.name), instructions: '另一个会话更新。', base_revision: 1, impact_token: impact.impact_token })
  const rejected = page.waitForResponse(r => r.url().endsWith(`/api/v1/skills/${skill.id}`) && r.request().method() === 'PUT')
  await dialog.getByRole('button', { name: '保存修改', exact: true }).click()
  expect((await rejected).status()).toBe(409)
  await expect(dialog.getByLabel(/^完整指令正文/)).toHaveValue('当前页面保留的草稿。')
  await expect(dialog.getByRole('button', { name: '保存修改', exact: true })).toBeDisabled()
  await dialog.getByRole('button', { name: '保留草稿并重新预览', exact: true }).click()
  await expect(dialog.getByRole('button', { name: '保存修改', exact: true })).toBeEnabled()
  const saved = page.waitForResponse(r => r.url().endsWith(`/api/v1/skills/${skill.id}`) && r.request().method() === 'PUT')
  await dialog.getByRole('button', { name: '保存修改', exact: true }).click()
  const response = await saved
  expect(response.status()).toBe(200)
  expect(response.request().postDataJSON().base_revision).toBe(2)
  expect((await api(page, 'GET', `/skills/${skill.id}`)).instructions).toBe('当前页面保留的草稿。')
})

test('TestSkillPersonalBindingEnablePreviewDisableAndReenable', async ({ page }) => {
  const account = await registerAccount(page)
  const skill = await createPersonal(page, '首次单项绑定')
  await page.goto(`/a/${account.id}/profile?tab=skills`)
  await page.getByLabel('选择个人技能').selectOption(skill.id)
  const enabled = page.waitForResponse(r => r.url().endsWith(`/skill-bindings/personal/${skill.id}`) && r.request().method() === 'PUT')
  await page.getByRole('button', { name: '启用所选个人技能', exact: true }).click()
  expect((await enabled).status()).toBe(200)
  const row = page.getByTestId(`skill-binding-${skill.id}`)
  await expect(row).toContainText('首次单项绑定')
  await expect(page.getByRole('heading', { name: '任务预算预览', exact: true })).toBeVisible()
  const taskChanged = page.waitForResponse(r => r.url().includes('/skill-context?') && new URL(r.url()).searchParams.get('task_type') === 'summary')
  await page.getByLabel('预览任务', { exact: true }).selectOption('summary')
  expect((await taskChanged).status()).toBe(200)
  await expect(page.getByText(/预览装配/)).toBeVisible()
  await row.getByRole('switch').click()
  await expect(row).toBeHidden()
  expect((await api(page, 'GET', `/accounts/${account.id}/skill-bindings`)).mine.count).toBe(0)
  await page.getByLabel('选择个人技能').selectOption(skill.id)
  await page.getByRole('button', { name: '启用所选个人技能', exact: true }).click()
  await expect(row).toBeVisible()
})


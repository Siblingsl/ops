test('TestSkillBuiltinReadOnlyDetailsAndIndependentCopy', async ({ page }) => {
  await registerAccount(page)
  await page.goto('/settings/skills')
  await page.getByRole('button', { name: '内置', exact: true }).click()
  const list = await api(page, 'GET', '/skills?view=library&scope=builtin')
  const builtin = list.items[0]
  const row = page.locator('div.flex.items-start.gap-3.px-5', { hasText: builtin.name })
  await expect(row.getByTitle('编辑', { exact: true })).toHaveCount(0)
  await expect(row.getByTitle('删除', { exact: true })).toHaveCount(0)
  await row.getByRole('button', { name: '查看详情', exact: true }).click()
  const detail = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '技能详情', exact: true }) })
  const full = await api(page, 'GET', `/skills/${builtin.id}`)
  await expect(detail).toContainText(full.instructions)
  await detail.getByRole('button', { name: '另存副本', exact: true }).click()
  const dialog = editor(page)
  const posted = page.waitForResponse(r => r.url().endsWith('/api/v1/skills') && r.request().method() === 'POST')
  await dialog.getByRole('button', { name: '创建技能', exact: true }).click()
  const response = await posted
  expect(response.status()).toBe(200)
  expect(response.request().postDataJSON()).toMatchObject({ scope: 'personal', copy_from_id: builtin.id })
  const personal = await api(page, 'GET', '/skills?view=library&scope=personal')
  expect(personal.items[0].origin).toBe('copied')
  const copy = await api(page, 'GET', `/skills/${personal.items[0].id}`)
  expect(copy.instructions).toBe(full.instructions)
  expect(copy.id).not.toBe(builtin.id)
  expect((await api(page, 'GET', `/skills/${builtin.id}`)).revision).toBe(full.revision)
})

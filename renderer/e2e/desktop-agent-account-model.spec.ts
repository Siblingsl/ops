import { expect, test } from '@playwright/test'
import { api, openDesktopAccountSwitcher, registerAccount } from './support'

test('桌面对话跟随当前账号，模型在输入台选择，跨账号历史不能混用', async ({ page }) => {
  const first = await registerAccount(page)
  const second = await api(page, 'POST', '/accounts', { platform: 'xhs', name: '第二个验收账号', content_format: 'image_note', type_note: '' })
  const provider = await api(page, 'POST', '/model-providers', { name: '模型选择验收', base_url: 'http://127.0.0.1:8297/v1', api_key: 'local-e2e-key', models: ['mock-agent-tested', 'mock-writer'] })
  await api(page, 'POST', `/model-providers/${provider.id}/selftest`, {})
  const alternate = await api(page, 'POST', '/model-providers', { name: '第二个模型验收', base_url: 'http://127.0.0.1:8297/v1', api_key: 'local-e2e-key', models: ['mock-writer'] })
  await api(page, 'POST', `/model-providers/${alternate.id}/selftest`, {})
  await api(page, 'PUT', '/model-routes', [{ task_type: 'agent_chat', provider_id: provider.id, model: 'mock-agent-tested' }])
  await page.addInitScript(() => {
    const ua = navigator.userAgent
    Object.defineProperty(navigator, 'userAgent', { configurable: true, get: () => `${ua} Electron/44.8.0` })
  })
  await page.goto(`/a/${first.id}`)
  await openDesktopAccountSwitcher(page)
  await page.getByTestId('desktop-context-menu').getByRole('tab', { name: /小红书/ }).click()
  await page.getByTestId('desktop-context-menu').getByRole('button', { name: '浏览器验收号', exact: true }).click()
  await page.getByRole('link', { name: 'AI 对话', exact: true }).click()
  const privacy = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '智能体隐私说明', exact: true }) })
  await privacy.getByRole('button', { name: '我知道了', exact: true }).click()
  await expect(page.getByRole('button', { name: '选择操作账号' })).toHaveCount(0)
  await page.getByRole('button', { name: '选择模型', exact: true }).click()
  const menu = page.getByRole('menu', { name: '选择模型' })
  await expect(menu).toBeVisible()
  await expect(page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '对话设置' }) })).toHaveCount(0)
  await expect(menu.getByRole('menuitemradio', { checked: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await page.getByRole('button', { name: '选择模型', exact: true }).click()
  await menu.getByRole('menuitemradio', { name: /mock-writer.*第二个模型验收/ }).click()
  await expect(menu).toHaveCount(0)
  await expect(page.getByRole('button', { name: '选择模型', exact: true })).toContainText('mock-writer')
  await page.getByRole('textbox', { name: '发送消息' }).fill('#text 测试当前账号')
  const firstRequest = page.waitForRequest(r => /\/agent\/conversations\/[^/]+\/messages$/.test(new URL(r.url()).pathname) && r.method() === 'POST')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  const firstPayload = (await firstRequest).postDataJSON()
  expect(firstPayload.account_id).toBe(first.id)
  expect(firstPayload.model).toMatchObject({ provider_id: alternate.id, model: 'mock-writer' })
  await page.waitForURL(/\/agent\/c\//)
  const oldConversation = page.url()
  const conversationID = oldConversation.split('/').pop()!
  await expect.poll(async () => (await api(page, 'GET', `/agent/conversations/${conversationID}`)).active_run).toBeNull()
  await expect(page.getByRole('button', { name: '选择模型', exact: true })).toBeEnabled()
  await page.getByRole('button', { name: '选择模型', exact: true }).click()
  await menu.getByRole('menuitemradio', { name: /mock-agent-tested.*模型选择验收/ }).click()
  await expect.poll(async () => (await api(page, 'GET', `/agent/conversations/${conversationID}`)).conversation.model).toBe('mock-agent-tested')
  await openDesktopAccountSwitcher(page)
  await page.getByTestId('desktop-context-menu').getByRole('tab', { name: /小红书/ }).click()
  await page.getByTestId('desktop-context-menu').getByRole('button', { name: '第二个验收账号', exact: true }).click()
  await page.getByRole('link', { name: 'AI 对话', exact: true }).click()
  await expect(page.locator('.desktop-agent-workbench-meta')).toContainText('第二个验收账号')
  await page.goto(oldConversation)
  await expect(page.getByTestId('agent-account-switched')).toContainText('浏览器验收号')
  await expect(page.getByRole('textbox', { name: '发送消息' })).toBeDisabled()
  await page.getByRole('button', { name: '为当前账号新建对话' }).click()
  await page.getByRole('textbox', { name: '发送消息' }).fill('#text 测试新账号')
  const secondRequest = page.waitForRequest(r => /\/agent\/conversations\/[^/]+\/messages$/.test(new URL(r.url()).pathname) && r.method() === 'POST')
  await page.getByRole('button', { name: '发送', exact: true }).click()
  expect((await secondRequest).postDataJSON().account_id).toBe(second.id)
})

import { expect, test } from '@playwright/test'
import { registerAccount } from './support'

test('桌面灵感入口贴边收起、长按拖动并在页面间保持位置', async ({ page }) => {
  const account = await registerAccount(page)
  await page.addInitScript(() => {
    const userAgent = navigator.userAgent
    Object.defineProperty(navigator, 'userAgent', { configurable: true, get: () => `${userAgent} Electron/44.8.0` })
  })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(`/a/${account.id}`)
  const button = page.getByRole('button', { name: '记一条灵感或存素材' })
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '随手记' }) })
  await page.mouse.move(500, 200)
  await expect(button).toHaveCSS('opacity', '0.55')
  await button.hover()
  await expect(button).toHaveCSS('opacity', '1')
  await expect.poll(() => button.evaluate((element) => element.getBoundingClientRect().right)).toBeLessThanOrEqual(1440.1)
  const before = (await button.boundingBox())!
  await page.mouse.move(before.x + 20, before.y + 20)
  await page.mouse.down()
  await expect(button).toHaveAttribute('data-dragging', 'true')
  await page.mouse.move(before.x - 80, before.y + 20)
  await expect(button).toHaveCSS('opacity', '1')
  expect(await button.evaluate((element) => element.getBoundingClientRect().right)).toBeLessThanOrEqual(1440)
  await page.waitForTimeout(300)
  await page.mouse.move(before.x + 20, 250, { steps: 5 })
  await expect(button).toHaveCSS('opacity', '1')
  expect(await button.evaluate((element) => element.getBoundingClientRect().right)).toBeLessThanOrEqual(1440)
  await page.mouse.up()
  await expect(dialog).toHaveCount(0)
  const moved = (await button.boundingBox())!
  expect(moved.y).toBeLessThan(before.y - 100)
  await page.getByRole('complementary', { name: '主导航' }).getByRole('link', { name: '作品', exact: true }).click()
  await expect(page).toHaveURL(new RegExp(`/a/${account.id}/works`))
  expect(Math.abs((await button.boundingBox())!.y - moved.y)).toBeLessThan(1)
  await button.click()
  await expect(dialog).toBeVisible()
  await page.mouse.move(500, 200)
  await expect(button).toHaveCSS('opacity', '1')
  await expect.poll(() => button.evaluate((element) => element.getBoundingClientRect().right)).toBeLessThanOrEqual(1440.1)
  expect(await button.evaluate((element) => Number(getComputedStyle(element).zIndex))).toBeGreaterThan(50)
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await page.locator('main').click({ position: { x: 20, y: 20 } })
  await expect(button).toHaveCSS('opacity', '0.55')
  await page.keyboard.press('Control+Shift+i')
  await expect(dialog).toBeVisible()
  await expect(button).toHaveCSS('opacity', '1')
})

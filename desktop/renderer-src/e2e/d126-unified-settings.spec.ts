async function electronPresentation(page: Page) {
  await page.addInitScript(() => {
    const agent = navigator.userAgent
    Object.defineProperty(navigator, 'userAgent', { configurable: true, get: () => `${agent} Electron/44.8.0` })
    Object.defineProperty(window, '__settingsIntents', { configurable: true, value: [] as string[] })
    window.open = ((url: string) => { (window as any).__settingsIntents.push(url); return null }) as typeof window.open
    const openListeners = new Set<() => void>()
    const stateListeners = new Set<(state: { dirty: boolean; busy: boolean }) => void>()
    Object.defineProperty(window, 'opsDesktopUI', { configurable: true, value: {
      onOpenSettings(listener: () => void) { openListeners.add(listener); return () => openListeners.delete(listener) },
      onLocalSettingsState(listener: (state: { dirty: boolean; busy: boolean }) => void) { stateListeners.add(listener); return () => stateListeners.delete(listener) },
    } })
    Object.defineProperty(window, '__emitNativeOpenSettings', { value: () => openListeners.forEach((listener) => listener()) })
    Object.defineProperty(window, '__emitNativeSettingsState', { value: (state: { dirty: boolean; busy: boolean }) => stateListeners.forEach((listener) => listener(state)) })
  })
}

const windowFor = (page: Page) => page.getByTestId('desktop-settings-window')
const section = (page: Page, name: string) => windowFor(page).getByRole('navigation', { name: '设置分类' }).getByRole('button', { name, exact: true })
async function openSettings(page: Page) {
  await page.getByRole('button', { name: /^用户菜单/ }).click()
  await page.getByRole('menuitem', { name: '设置…', exact: true }).click()
  await expect(windowFor(page)).toBeVisible()
}


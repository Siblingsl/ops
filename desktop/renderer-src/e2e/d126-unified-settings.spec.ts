test('D-126 未保存确认、取消保留输入、保存中保护和失败恢复', async ({ page }) => {
  await registerAccount(page)
  await electronPresentation(page)
  await page.goto('/settings/daily')
  const settings = windowFor(page)
  const hour = settings.getByLabel('后台生成小时（北京时间）')
  await expect(hour).toBeVisible()
  const original = await hour.inputValue()
  const changed = String((Number(original) + 1) % 24)
  await hour.fill(changed)
  await selectDesktopSetting(page, '偏好设置')
  const discard = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: '放弃未保存的设置？' }) })
  await expect(discard).toBeVisible()
  await discard.getByRole('button', { name: '取消', exact: true }).click()
  await expect(hour).toHaveValue(changed)
  await expect(page).toHaveURL(/\/settings\/daily$/)
  await page.route('**/api/v1/daily-settings', (route) => route.request().method() === 'PUT' ? route.fulfill({ status: 500, json: { error: { code: 'internal', message: '测试保存失败' } } }) : route.continue())
  await settings.getByRole('button', { name: '保存默认设置' }).click()
  await expect(page.getByText('测试保存失败', { exact: true })).toBeVisible()
  await expect(hour).toHaveValue(changed)
  await page.unroute('**/api/v1/daily-settings')
  let release!: () => void
  const pending = new Promise<void>((resolve) => { release = resolve })
  await page.route('**/api/v1/daily-settings', async (route) => { if (route.request().method() === 'PUT') await pending; await route.continue() })
  await settings.getByRole('button', { name: '保存默认设置' }).click()
  await selectDesktopSetting(page, '偏好设置')
  await expect(page.getByText('正在保存设置，请稍候再离开')).toBeVisible()
  await expect(hour).toBeVisible()
  release()
  await expect(settings.getByText('有未保存的修改')).toHaveCount(0)
  await page.unroute('**/api/v1/daily-settings')
  await selectDesktopSetting(page, 'AI 用量与成本')
  await settings.getByRole('switch', { name: '启用每日 token 上限' }).click()
  await settings.getByLabel('每日上限（token）').fill('250000')
  await settings.getByRole('button', { name: '保存每日上限' }).click()
  await expect.poll(async () => (await api(page, 'GET', '/settings')).ai_limit.daily_tokens).toBe(250000)
  await selectDesktopSetting(page, '敏感词库')
  await settings.getByLabel(/^敏感词/).fill('未保存的测试词')
  await settings.getByRole('button', { name: '关闭设置' }).click()
  await expect(discard).toBeVisible()
  await discard.getByRole('button', { name: '放弃修改', exact: true }).click()
  await expect(settings).toHaveCount(0)
})

